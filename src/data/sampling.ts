export const getSamplingsByProject = (projectId: string): Sampling[] => {
  return samplings.filter(s => s.projectId === projectId);
};

export const getSamplingsByArrival = (arrivalId: string): Sampling[] => {
  return samplings.filter(s => s.arrivalId === arrivalId);
};

export const getSamplingById = (id: string): Sampling | undefined => {
  return samplings.find(s => s.id === id);
};

export const getSamplingsByStatus = (status: Sampling['status']): Sampling[] => {
  return samplings.filter(s => s.status === status);
};

